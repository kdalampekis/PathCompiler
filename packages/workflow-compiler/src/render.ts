import { stringify } from "yaml";
import {
  COMPILER_VERSION,
  type CompiledWorkflows,
  type Documentation,
  type DocumentationRecord,
  DocumentationSchema,
} from "./schema.js";

export const EXPORT_FORMATS = ["json", "yaml", "markdown"] as const;
export type ExportFormat = (typeof EXPORT_FORMATS)[number];

/** Marks generated Markdown; exporters only replace files carrying it. */
export const GENERATED_MARKER = "<!-- Generated by PathCompiler";

/** Escapes approved text so it renders literally (no HTML, links or emphasis). */
export function escapeMarkdown(text: string): string {
  return text
    .replace(/\s+/g, " ")
    .trim()
    .replace(/[\\`*_{}[\]()<>#+!|~]/g, (character) => `\\${character}`);
}

/** One workflow as Markdown, derived only from its compiled documentation record. */
export function renderWorkflowMarkdown(
  record: DocumentationRecord,
  options: { level?: 1 | 2 } = {},
): string {
  const heading = "#".repeat(options.level ?? 1);
  const lines = [
    `${heading} ${escapeMarkdown(record.title)}`,
    "",
    `\`${record.id}\` · revision \`${record.revision.slice(0, 19)}\``,
    "",
  ];
  if (record.description) lines.push(escapeMarkdown(record.description), "");
  lines.push(
    `**Where:** ${record.entrypoints.map(escapeMarkdown).join(", ")}`,
    "",
  );
  if (record.roles.length)
    lines.push(`**Who:** ${record.roles.map(escapeMarkdown).join(", ")}`, "");
  if (record.prerequisites.length)
    lines.push(
      "**Before you start:**",
      "",
      ...record.prerequisites.map((item) => `- ${escapeMarkdown(item)}`),
      "",
    );
  lines.push(`${heading}# Steps`, "");
  record.steps.forEach((step, index) => {
    lines.push(
      `${index + 1}. ${escapeMarkdown(step.text)}${step.optional ? " _(optional)_" : ""}`,
    );
    if (step.expected)
      lines.push(`   - Then: ${escapeMarkdown(step.expected)}`);
    for (const branch of step.branches)
      lines.push(
        `   - If ${escapeMarkdown(branch.when)}, continue at step ${
          record.steps.findIndex((item) => item.id === branch.next) + 1
        }.`,
      );
  });
  lines.push("", `**Done when:** ${escapeMarkdown(record.completion)}`, "");
  return `${lines.join("\n")}`;
}

/** Catalog of every approved workflow, for bundling or review. */
export function renderCatalogMarkdown(input: Documentation): string {
  const documentation = DocumentationSchema.parse(input);
  return [
    `${GENERATED_MARKER} ${COMPILER_VERSION} from approved workflows. Do not edit; rebuild. -->`,
    "",
    "# Product workflows",
    "",
    documentation.workflows.length
      ? documentation.workflows
          .map(
            (record) =>
              `- [${escapeMarkdown(record.title)}](#${record.id.replace(/[^a-z0-9]+/g, "-")}) \`${record.id}\``,
          )
          .join("\n")
      : "No approved workflows.",
    "",
    ...documentation.workflows.map(
      (record) =>
        `<a id="${record.id.replace(/[^a-z0-9]+/g, "-")}"></a>\n\n${renderWorkflowMarkdown(record, { level: 2 })}`,
    ),
  ].join("\n");
}

/**
 * Deterministic static export: relative paths under `generated/` and contents.
 * JSON is what the SDK's static transport reads; YAML mirrors it; Markdown is a
 * human-readable catalog.
 */
export function exportArtifacts(
  compiled: CompiledWorkflows,
  formats: readonly ExportFormat[] = ["json"],
): [string, string][] {
  const files: [string, string][] = [];
  const named = [
    ["search-index", compiled.searchIndex],
    ["runtime-manifest", compiled.runtimeManifest],
    ["documentation", compiled.documentation],
  ] as const;
  for (const format of [...new Set(formats)].sort())
    if (format === "json")
      for (const [name, value] of named)
        files.push([
          `generated/${name}.json`,
          `${JSON.stringify(value, null, 2)}\n`,
        ]);
    else if (format === "yaml")
      for (const [name, value] of named)
        files.push([
          `generated/${name}.yaml`,
          stringify(value, { aliasDuplicateObjects: false, lineWidth: 0 }),
        ]);
    else
      files.push([
        "generated/workflows.md",
        renderCatalogMarkdown(compiled.documentation),
      ]);
  return files;
}

/**
 * Help-center pages: one Markdown file per approved workflow plus an index.
 * Pages are renderers of approved workflows, never their source of truth.
 */
export function renderHelpPages(input: Documentation): [string, string][] {
  const documentation = DocumentationSchema.parse(input);
  const header = (what: string) =>
    `${GENERATED_MARKER} ${COMPILER_VERSION} from ${what}. Do not edit; change the workflow and re-export. -->\n\n`;
  const pages: [string, string][] = documentation.workflows.map((record) => [
    `${record.id}.md`,
    `${header(`approved workflow ${record.id} (${record.revision})`)}${renderWorkflowMarkdown(record)}`,
  ]);
  const byDomain = new Map<string, typeof documentation.workflows>();
  for (const record of documentation.workflows)
    byDomain.set(record.domain, [
      ...(byDomain.get(record.domain) ?? []),
      record,
    ]);
  const index = [
    `${header("approved workflows")}# Help`,
    "",
    ...(documentation.workflows.length
      ? [...byDomain].flatMap(([domain, records]) => [
          `## ${escapeMarkdown(domain)}`,
          "",
          ...records.map(
            (record) =>
              `- [${escapeMarkdown(record.title)}](./${record.id}.md)`,
          ),
          "",
        ])
      : ["No approved workflows yet.", ""]),
  ].join("\n");
  return [["index.md", index], ...pages];
}

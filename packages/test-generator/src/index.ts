import {
  type FormalExpr,
  type FormalProductModel,
  f,
  parseFormalModel,
} from "@pathcompiler/formal-model";
import type { ProductGraph } from "@pathcompiler/graph-core";
import type {
  FormalValue,
  Plan,
  ProductReasoner,
} from "@pathcompiler/reasoner-core";
import type {
  WorkflowCondition,
  WorkflowTerminalCondition,
} from "@pathcompiler/workflow-ir";
import { z } from "zod";

/**
 * Automated test generation (reasoning spec §36): formal plans become
 * positive Playwright candidates, unreachability becomes negative ones. Every
 * file is a candidate for human review and is written next to, never into,
 * the product's own tests.
 */
export const GENERATED_TEST_MARKER =
  "// Generated by PathCompiler (reasoning spec §36): a candidate test. Review before adopting.";

/** How the product sets each context variable in a browser (demo controls, test users…). */
export const TestSetupSchema = z.strictObject({
  schemaVersion: z.literal(1),
  /** Route each test starts from. */
  start: z.string().startsWith("/"),
  context: z.record(
    z.string(),
    z.discriminatedUnion("control", [
      z.strictObject({
        control: z.literal("select"),
        /** `data-pathcompiler` target of the select. */
        target: z.string().min(1),
        /** Model value → option value; values not listed cannot be set. */
        values: z.record(z.string(), z.string()),
      }),
      z.strictObject({
        control: z.literal("checkbox"),
        target: z.string().min(1),
      }),
    ]),
  ),
});
export type TestSetup = z.infer<typeof TestSetupSchema>;
export type GeneratedTest = {
  file: string;
  kind: "positive" | "negative";
  goal: string;
  capabilityId?: string;
  context: Record<string, FormalValue>;
  /** Plan actions the test replays. */
  actions: string[];
  /** True when the completion signal is a fallback ("no error shown"). */
  weakAssertion: boolean;
  content: string;
};
export type GenerationReport = {
  schemaVersion: 1;
  reviewRequired: true;
  tests: GeneratedTest[];
  skipped: { goal: string; reason: string }[];
};

const compare = (a: string, b: string) => (a < b ? -1 : a > b ? 1 : 0);
const quote = (value: string) => JSON.stringify(value);
const locator = (target: string) =>
  `page.locator(${quote(`[data-pathcompiler="${target}"]`)}).first()`;

/** Starts every plan from an empty product: no entity exists yet. */
export function freshStateModel(
  input: FormalProductModel,
  fresh?: Record<string, FormalValue>,
): FormalProductModel {
  const model = parseFormalModel(input);
  // Formal abstraction names existence variables `<entity>_exists`.
  const values =
    fresh ??
    Object.fromEntries(
      model.variables
        .filter((item) => item.scope === "state" && item.id.endsWith("_exists"))
        .map((item) => [item.id, false]),
    );
  const extra: FormalExpr[] = Object.entries(values).map(([id, value]) =>
    f.is(id, value),
  );
  return extra.length === 0
    ? model
    : { ...model, initial: f.and(model.initial, ...extra) };
}

function setupLines(
  setup: TestSetup | undefined,
  context: Record<string, FormalValue>,
): { lines: string[]; missing: string[] } {
  const lines = [`  await page.goto(${quote(setup?.start ?? "/")});`];
  const missing: string[] = [];
  for (const [id, value] of Object.entries(context).sort(([a], [b]) =>
    compare(a, b),
  )) {
    const control = setup?.context[id];
    if (!control) {
      missing.push(`${id}=${String(value)}`);
      continue;
    }
    if (control.control === "checkbox") {
      lines.push(
        `  await ${locator(control.target)}.setChecked(${value === true});`,
        `  await expect(${locator(control.target)}).${value === true ? "toBeChecked" : "not.toBeChecked"}();`,
      );
      continue;
    }
    const option = control.values[String(value)];
    if (option === undefined) {
      missing.push(`${id}=${String(value)}`);
      continue;
    }
    lines.push(
      `  await ${locator(control.target)}.selectOption(${quote(option)});`,
      `  await expect(${locator(control.target)}).toHaveValue(${quote(option)});`,
    );
  }
  // Context changes re-render the page; let it settle before acting.
  if (lines.length > 1)
    lines.push('  await page.waitForLoadState("networkidle");');
  return { lines, missing };
}

function stepCall(
  graph: ProductGraph,
  model: FormalProductModel,
  step: Plan["steps"][number],
): string | undefined {
  const target = step.semanticTarget;
  if (!target) return undefined;
  const node = graph.getNode(`ui:${target}`);
  const label =
    typeof node?.data?.label === "string" ? node.data.label : target;
  if (node?.data?.kind === "input") {
    if (node.data.tag === "select") {
      // A select action that assigns an enum value picks that option.
      const assigned = model.actions
        .find((action) => action.id === step.actionId)
        ?.effects.find((effect) => effect.value.type === "const");
      const value =
        assigned?.value.type === "const" &&
        typeof assigned.value.value === "string" &&
        !assigned.variable.endsWith("_entered")
          ? assigned.value.value.toLowerCase()
          : undefined;
      return value === undefined
        ? "selectOption({ index: 0 })"
        : `selectOption(${quote(value)})`;
    }
    const sample = /email/i.test(target)
      ? "generated@example.test"
      : `Generated ${label}`;
    return `fill(${quote(sample)})`;
  }
  return "click()";
}

function terminalCheck(
  input: WorkflowTerminalCondition | undefined,
  negated: boolean,
): { line: string; weak: boolean } {
  // All of several conditions: assert each (or, negated, the first).
  if (input && "all" in input) {
    const checks = (negated ? input.all.slice(0, 1) : input.all).map((item) =>
      terminalCheck(item, negated),
    );
    return {
      line: checks.map((item) => item.line).join("\n"),
      weak: checks.some((item) => item.weak),
    };
  }
  // Any of several: no single assertion is right, so fall back.
  const terminal: WorkflowCondition | undefined =
    input && "any" in input ? undefined : input;
  const not = negated ? "not." : "";
  if (terminal?.type === "element_text")
    return {
      line: `  await expect(${locator(terminal.target)}).${not}${terminal.match === "exact" ? "toHaveText" : "toContainText"}(${quote(terminal.text)});`,
      weak: false,
    };
  if (terminal?.type === "element_count" && !negated)
    return {
      line: `  await expect(page.locator(${quote(`[data-pathcompiler="${terminal.target}"]`)})).toHaveCount(${terminal.count});`,
      weak: false,
    };
  if (
    terminal?.type === "element_state" &&
    terminal.state === "visible" &&
    !negated
  )
    return {
      line: `  await expect(${locator(terminal.target)}).toBeVisible();`,
      weak: false,
    };
  return {
    line: negated
      ? "  // Review: no completion signal is known; the goal is checked only through the blocked steps above."
      : `  // Review: no completion signal is known; this only checks that the dialog closed.\n  await expect(page.getByRole("dialog")).toHaveCount(0);`,
    weak: true,
  };
}

const HELPER = `async function attempt(
  target: Locator,
  act: (target: Locator) => Promise<unknown>,
): Promise<boolean> {
  // A missing, vanishing or disabled control means the step is blocked, as expected.
  if ((await target.count()) === 0) return false;
  const enabled = await target
    .isEnabled({ timeout: 2_000 })
    .catch(() => false);
  if (!enabled) return false;
  await act(target);
  return true;
}`;

export function renderPositiveTest(input: {
  name: string;
  plan: Plan;
  model: FormalProductModel;
  graph: ProductGraph;
  setup?: TestSetup;
  terminal?: WorkflowTerminalCondition;
}): { content: string; weak: boolean; missing: string[] } {
  const setup = setupLines(input.setup, input.plan.context);
  const body = input.plan.steps.flatMap((step) => {
    const call = stepCall(input.graph, input.model, step);
    return call
      ? [
          `  // ${step.actionId}`,
          `  await ${locator(step.semanticTarget as string)}.${call};`,
        ]
      : [];
  });
  const terminal = terminalCheck(input.terminal, false);
  return {
    content: [
      GENERATED_TEST_MARKER,
      'import { expect, test } from "@playwright/test";',
      "",
      `test(${quote(input.name)}, async ({ page }) => {`,
      ...setup.lines,
      ...body,
      terminal.line,
      "});",
      "",
    ].join("\n"),
    weak: terminal.weak,
    missing: setup.missing,
  };
}

export function renderNegativeTest(input: {
  name: string;
  /** A plan that reaches the goal in an allowed context. */
  plan: Plan;
  /** The context in which the goal must be unreachable. */
  context: Record<string, FormalValue>;
  model: FormalProductModel;
  graph: ProductGraph;
  setup?: TestSetup;
  terminal?: WorkflowTerminalCondition;
}): { content: string; weak: boolean; missing: string[] } {
  const setup = setupLines(input.setup, input.context);
  const body = input.plan.steps.flatMap((step) => {
    const call = stepCall(input.graph, input.model, step);
    return call
      ? [
          `  // ${step.actionId}`,
          `  if (!(await attempt(${locator(step.semanticTarget as string)}, (target) => target.${call}))) return;`,
        ]
      : [];
  });
  const terminal = terminalCheck(input.terminal, true);
  return {
    content: [
      GENERATED_TEST_MARKER,
      'import { expect, type Locator, test } from "@playwright/test";',
      "",
      HELPER,
      "",
      `test(${quote(input.name)}, async ({ page }) => {`,
      ...setup.lines,
      "  // Replays a path that works in an allowed context; here it must stop or fail.",
      ...body,
      terminal.line,
      "});",
      "",
    ].join("\n"),
    weak: terminal.weak,
    missing: setup.missing,
  };
}

/**
 * Positive tests for every reachable capability goal (from an empty
 * product), and negative tests for every role value and flag the reasoner
 * proves blocks the goal. Contexts the setup cannot establish are skipped.
 */
export async function generateTests(input: {
  reasoner: ProductReasoner;
  model: FormalProductModel;
  graph: ProductGraph;
  setup?: TestSetup;
  /** Completion signals per capability (e.g. test-backed workflow terminals). */
  terminals?: Record<string, WorkflowTerminalCondition>;
  goals?: string[];
  maxDepth?: number;
  timeoutMs?: number;
}): Promise<GenerationReport> {
  const model = freshStateModel(input.model);
  const limits = {
    ...(input.maxDepth === undefined ? {} : { maxDepth: input.maxDepth }),
    ...(input.timeoutMs === undefined ? {} : { timeoutMs: input.timeoutMs }),
  };
  const roleVariable = model.variables.find(
    (item) => item.id === "role" && item.scope === "context",
  );
  const flags = model.variables.filter(
    (item) => item.scope === "context" && item.type === "boolean",
  );
  const tests: GeneratedTest[] = [];
  const skipped: GenerationReport["skipped"] = [];
  const goals = model.goals
    .filter(
      (goal) =>
        goal.capabilityId && (!input.goals || input.goals.includes(goal.id)),
    )
    .sort((a, b) => compare(a.id, b.id));
  for (const goal of goals) {
    const capabilityId = goal.capabilityId as string;
    const terminal = input.terminals?.[capabilityId];
    const found = await input.reasoner.findPlan(model, {
      goal: goal.id,
      ...limits,
    });
    if (found.status !== "found") {
      skipped.push({
        goal: goal.id,
        reason: `No plan from an empty product (${found.status}).`,
      });
      continue;
    }
    const positive = renderPositiveTest({
      name: `${goal.id} is reachable (${capabilityId})`,
      plan: found.plan,
      model,
      graph: input.graph,
      ...(input.setup ? { setup: input.setup } : {}),
      ...(terminal ? { terminal } : {}),
    });
    if (positive.missing.length > 0)
      skipped.push({
        goal: goal.id,
        reason: `The setup cannot establish ${positive.missing.join(", ")}.`,
      });
    else
      tests.push({
        file: `${goal.id}.positive.spec.ts`,
        kind: "positive",
        goal: goal.id,
        capabilityId,
        context: found.plan.context,
        actions: found.plan.steps.map((step) => step.actionId),
        weakAssertion: positive.weak,
        content: positive.content,
      });
    // Negative candidates: one context value at a time, the rest as in the
    // positive plan's witness.
    const blocking: Record<string, FormalValue>[] = [
      ...(roleVariable?.type === "enum"
        ? roleVariable.values.map((value) => ({ role: value }))
        : []),
      ...flags.map((flag) => ({ [flag.id]: false })),
    ];
    for (const change of blocking) {
      const context = { ...found.plan.context, ...change };
      if (
        Object.entries(change).every(
          ([id, value]) => found.plan.context[id] === value,
        )
      )
        continue;
      const reach = await input.reasoner.checkReachability(model, {
        goal: goal.id,
        context,
        ...limits,
      });
      if (reach.status !== "unreachable") continue;
      const [id, value] = Object.entries(change)[0] as [string, FormalValue];
      const negative = renderNegativeTest({
        name: `${goal.id} is unreachable with ${id}=${String(value)}`,
        plan: found.plan,
        context,
        model,
        graph: input.graph,
        ...(input.setup ? { setup: input.setup } : {}),
        ...(terminal ? { terminal } : {}),
      });
      if (negative.missing.length > 0) {
        skipped.push({
          goal: goal.id,
          reason: `Negative ${id}=${String(value)}: the setup cannot establish ${negative.missing.join(", ")}.`,
        });
        continue;
      }
      tests.push({
        file: `${goal.id}.negative.${id}-${String(value).toLowerCase()}.spec.ts`,
        kind: "negative",
        goal: goal.id,
        capabilityId,
        context,
        actions: found.plan.steps.map((step) => step.actionId),
        weakAssertion: negative.weak,
        content: negative.content,
      });
    }
  }
  return { schemaVersion: 1, reviewRequired: true, tests, skipped };
}
